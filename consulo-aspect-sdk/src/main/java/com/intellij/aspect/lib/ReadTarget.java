package com.intellij.aspect.lib;

import com.google.devtools.intellij.ideinfo.IntellijIdeInfo.TargetIdeInfo;
import com.google.protobuf.TextFormat;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.function.Consumer;

/**
 * consulo: top-level functions of upstream sdk/lib/readtarget.kt.
 */
public final class ReadTarget {
    // consulo: upstream is a lazy top-level value
    private static final class ParserHolder {
        private static final TextFormat.Parser PARSER =
            TextFormat.Parser
                .newBuilder()
                .setAllowUnknownFields(true)
                .build();
    }

    private ReadTarget() {
    }

    // Read a textproto message generated by this aspect from a file
    public static @Nullable TargetIdeInfo readTargetFromFile(Path file) {
        return readTargetFromFile(file, it -> {
        });
    }

    // Read a textproto message generated by this aspect from a file
    public static @Nullable TargetIdeInfo readTargetFromFile(Path file, Consumer<@Nullable String> logErrorMessage) {
        TargetIdeInfo.Builder builder = TargetIdeInfo.newBuilder();

        try {
            ParserHolder.PARSER.merge(new String(Files.readAllBytes(file), StandardCharsets.UTF_8), builder);
        }
        catch (IOException e) {
            logErrorMessage.accept(e.getMessage());
            return null;
        }

        return builder.build();
    }

    // Read a `<name>=<value>` environment file generated by this aspect (e.g. CToolchainIdeInfo.xcode_info)
    public static @Nullable Map<String, String> readEnvFromFile(Path file) {
        String text;
        try {
            text = new String(Files.readAllBytes(file), StandardCharsets.UTF_8);
        }
        catch (IOException e) {
            return null;
        }

        Map<String, String> result = new LinkedHashMap<>();
        for (String entry : text.split("\0", -1)) {
            if (entry.isEmpty()) {
                continue;
            }
            // consulo: Kotlin substringBefore('=') / substringAfter('=') return the whole string without a '='
            int index = entry.indexOf('=');
            if (index == -1) {
                result.put(entry, entry);
            }
            else {
                result.put(entry.substring(0, index), entry.substring(index + 1));
            }
        }
        return result;
    }
}

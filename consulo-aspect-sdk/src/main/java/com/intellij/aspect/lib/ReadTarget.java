package com.intellij.aspect.lib;

import com.google.devtools.intellij.ideinfo.IntellijIdeInfo.TargetIdeInfo;
import com.google.protobuf.TextFormat;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.function.Consumer;

/**
 * consulo: top-level functions of upstream sdk/lib/readtarget.kt.
 */
public final class ReadTarget {
    private ReadTarget() {
    }

    // Read a textproto message generated by this aspect from a file
    public static @Nullable TargetIdeInfo readTargetFromFile(Path file) {
        return readTargetFromFile(file, it -> {
        });
    }

    // Read a textproto message generated by this aspect from a file
    public static @Nullable TargetIdeInfo readTargetFromFile(Path file, Consumer<@Nullable String> logErrorMessage) {
        TargetIdeInfo.Builder builder = TargetIdeInfo.newBuilder();
        TextFormat.Parser parser =
            TextFormat.Parser
                .newBuilder()
                .setAllowUnknownFields(true)
                .build();
        try {
            parser.merge(new String(Files.readAllBytes(file), StandardCharsets.UTF_8), builder);
        }
        catch (IOException e) {
            logErrorMessage.accept(e.getMessage());
            return null;
        }
        return builder.build();
    }
}

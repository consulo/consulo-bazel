package com.intellij.aspect.lib;

import static com.intellij.aspect.lib.PathUtil.asBazelPath;

import com.google.devtools.intellij.aspect.Aspect.AspectConfiguration;
import com.google.devtools.intellij.aspect.Aspect.Module;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

// consulo: declared in upstream sdk/lib/definition.kt. The top-level declarations of that file are in
// {@link Definition}.

/**
 * Describes how an aspect can be configured, derived from an {@link AspectConfiguration} message as
 * generated by {@code //private/rules:aspect_config.bzl}.
 */
public final class AspectDefinition {
    private static final String DEFAULT_ASPECT_NAME = "intellij_aspect";

    public record Location(Path file, String name) {
        public Location {
            if (file.isAbsolute()) {
                throw new IllegalArgumentException("aspect file must be relative: " + file);
            }
        }

        @Override
        public String toString() {
            Path parent = file.getParent();
            String label;
            if (parent == null) {
                label = ":" + file.getFileName();
            }
            else {
                label = asBazelPath(parent) + ":" + file.getFileName();
            }

            return label + "%" + name;
        }
    }

    private final AspectConfiguration myProto;
    private final Location myLocation;

    private AspectDefinition(AspectConfiguration proto) {
        myProto = proto;
        myLocation = new Location(
            Path.of(proto.getFile()),
            proto.getName().isEmpty() ? DEFAULT_ASPECT_NAME : proto.getName()
        );
    }

    public AspectConfiguration getProto() {
        return myProto;
    }

    /**
     * The location of the aspect once deployed.
     */
    public Location getLocation() {
        return myLocation;
    }

    /**
     * All modules known to this aspect configuration.
     */
    public List<Module> getModules() {
        return myProto.getModulesList();
    }

    /**
     * All modules that will be enabled for the rule set.
     */
    List<Module> modulesFor(Iterable<Rules> rulesets) {
        Set<String> names = new HashSet<>();
        for (Rules ruleset : rulesets) {
            names.add(ruleset.name());
        }

        List<Module> result = new ArrayList<>();
        for (Module module : getModules()) {
            if (module.getRulesetsList().isEmpty() || module.getRulesetsList().stream().anyMatch(names::contains)) {
                result.add(module);
            }
        }
        return result;
    }

    /**
     * Reads an aspect definition bundled as a resource of this jar.
     */
    static AspectDefinition fromResource(String name) throws IOException {
        InputStream stream = AspectDefinition.class.getResourceAsStream(name);
        if (stream == null) {
            throw new IOException("bundled aspect definition not found: " + name);
        }

        AspectConfiguration proto;
        try (stream) {
            proto = ProtoUtil.parseTextProto(new String(stream.readAllBytes(), StandardCharsets.UTF_8), AspectConfiguration.class);
        }

        return new AspectDefinition(proto);
    }
}

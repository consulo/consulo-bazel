package org.jetbrains.bazel.utils;

import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

public record ExecutableInfo(
    Path binary,
    Path workingDir,
    List<String> args,
    Map<String, String> envVars,
    List<Path> directoriesToCreate
) {
    // consulo: overload for the upstream default argument directoriesToCreate = emptyList()
    public ExecutableInfo(Path binary, Path workingDir, List<String> args, Map<String, String> envVars) {
        this(binary, workingDir, args, envVars, List.of());
    }

    // consulo: Kotlin Path.createDirectories() throws IOException unchecked, here as UncheckedIOException
    public void createRequiredDirectories() {
        for (Path directory : directoriesToCreate) {
            try {
                Files.createDirectories(directory);
            }
            catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }
    }

    public @Nullable Path getTestXml() {
        String value = envVars.get(XML_OUTPUT_FILE);
        return value != null ? Path.of(value) : null;
    }

    /**
     * Parses the content of the run script generated by `bazel run --script_path` into the {@link ExecutableInfo} needed to attach a
     * native debugger.
     * The script is a Bash script, or a `cmd` script on Windows. For a test, the script starts a test wrapper:
     * <a href="https://github.com/bazelbuild/bazel/blob/master/tools/test/test-setup.sh">test-setup.sh</a>, or
     * <a href="https://github.com/bazelbuild/bazel/blob/master/tools/test/windows/tw.cc">tw.exe</a> on Windows.
     * The debugger starts the test binary directly, so this function applies the environment changes of the test wrapper.
     */
    public static ExecutableInfo fromBazelRunScript(String scriptContent) throws UnexpectedScriptContentException {
        // Bazel 9.2 and earlier write no newline after the last line, later versions write one.
        String content = removeSuffix(scriptContent, "\n");
        ScriptPathContent script = content.startsWith("#!") ? parseBashScript(content) : parseCmdScript(content);
        return script.env().containsKey(TEST_SRCDIR) ? toTestExecutableInfo(script) : toBinaryExecutableInfo(script);
    }

    private record ScriptPathContent(
        Path execRoot,
        Map<String, String> env,
        List<String> command,
        char pathSeparator
    ) {
    }

    /**
     * Parses a script of this form:
     * <pre>
     * #!/bin/bash
     * cd &lt;dir&gt; &amp;&amp; \
     *   exec env \
     *     -u &lt;NAME&gt; \
     *     &lt;NAME&gt;=&lt;value&gt; \
     *   &lt;command&gt; "$@"
     * </pre>
     */
    private static ScriptPathContent parseBashScript(String content) throws UnexpectedScriptContentException {
        List<String> lines = lines(content);
        if (lines.size() < 4) {
            throw new UnexpectedScriptContentException("Expected at least 4 lines, actual: " + lines);
        }
        // lines[0] is `#!/bin/bash`
        List<String> cdLine = parseBashWords(removeSuffix(lines.get(1), "\\"));
        if (cdLine.size() < 2 || !cdLine.get(0).equals("cd")) {
            throw new UnexpectedScriptContentException("Unable to read execution root from script.");
        }
        // lines[2] is `exec env \`
        Map<String, String> env = new LinkedHashMap<>();
        for (String line : lines.subList(3, lines.size() - 1)) {
            List<String> words = parseBashWords(removeSuffix(line, "\\"));
            if (!words.isEmpty() && words.get(0).equals("-u")) {
                continue;
            }
            if (words.size() != 1) {
                throw new UnexpectedScriptContentException("Expected one env var per line, actual: " + words);
            }
            String[] assignment = parseEnvAssignment(words.get(0));
            env.put(assignment[0], assignment[1]);
        }
        return new ScriptPathContent(Path.of(cdLine.get(1)), env, dropLast(parseBashWords(lines.get(lines.size() - 1))), ':');
    }

    // consulo: upstream returns Pair<String, String>, here {name, value}
    private static String[] parseEnvAssignment(String assignment) throws UnexpectedScriptContentException {
        String[] parts = assignment.split("=", 2);
        if (parts.length != 2) {
            throw new UnexpectedScriptContentException("Expected <NAME>=<value>, actual: " + assignment);
        }
        return parts;
    }

    /**
     * Parses a script of this form:
     * <pre>
     * &#64;echo off
     *   cd /d &lt;dir&gt;
     *   SET &lt;NAME&gt;=
     *   SET &lt;NAME&gt;=&lt;value&gt;
     *   &lt;command&gt; %*
     * </pre>
     */
    private static ScriptPathContent parseCmdScript(String content) throws UnexpectedScriptContentException {
        List<String> lines = new ArrayList<>();
        for (String it : lines(content)) {
            lines.add(it.stripLeading());
        }
        if (lines.size() < 3) {
            throw new UnexpectedScriptContentException("Expected at least 3 lines, actual: " + lines.size());
        }
        // lines[0] is `@echo off`
        if (!lines.get(1).startsWith("cd /d ")) {
            throw new UnexpectedScriptContentException("Unable to read execution root from script.");
        }
        Map<String, String> env = new LinkedHashMap<>();
        for (String line : lines.subList(2, lines.size() - 1)) {
            if (!line.startsWith("SET ")) {
                continue;
            }
            String[] assignment = parseEnvAssignment(line.substring("SET ".length()));
            String name = assignment[0];
            String value = assignment[1];
            if (value.isEmpty()) {
                env.remove(name);
            }
            else {
                env.put(name, value);
            }
        }
        return new ScriptPathContent(
            Path.of(lines.get(1).substring("cd /d ".length())),
            env,
            dropLast(parseCmdWords(lines.get(lines.size() - 1))),
            ';'
        );
    }

    private static ExecutableInfo toBinaryExecutableInfo(ScriptPathContent receiver) throws UnexpectedScriptContentException {
        List<String> command = receiver.command();
        if (command.isEmpty()) {
            throw new UnexpectedScriptContentException("Expected an executable for regular binary.");
        }
        return new ExecutableInfo(
            /* binary = */ Path.of(command.get(0)),
            /* workingDir = */ receiver.execRoot(),
            /* args = */ List.copyOf(command.subList(1, command.size())),
            /* envVars = */ receiver.env()
        );
    }

    // See https://github.com/bazelbuild/bazel/blob/master/tools/test/test-setup.sh
    private static ExecutableInfo toTestExecutableInfo(ScriptPathContent receiver) throws UnexpectedScriptContentException {
        List<String> command = receiver.command();
        Map<String, String> env = receiver.env();
        Path execRoot = receiver.execRoot();
        if (command.size() < 2) {
            throw new UnexpectedScriptContentException("Expected at least 2 arguments for test binary, actual: " + command);
        }
        String workspaceName = env.get(TEST_WORKSPACE);
        if (workspaceName == null) {
            throw new UnexpectedScriptContentException("Unable to read workspace name from script.");
        }

        Map<String, String> testEnv = new LinkedHashMap<>(env);
        testEnv.put("BAZEL_TEST", "1");
        for (String name : RELATIVE_PATH_VARS_TO_RESOLVE) {
            testEnv.computeIfPresent(name, (key, value) -> execRoot.resolve(value).toString());
        }
        testEnv.keySet().removeAll(VARS_TO_UNSET);
        String testTmpDir = testEnv.get(TEST_TMPDIR);
        if (testTmpDir != null) {
            testEnv.put("GTEST_TMP_DIR", testTmpDir);
        }
        String path = testEnv.get("PATH");
        if (path != null) {
            testEnv.put("PATH", "." + receiver.pathSeparator() + path);
        }

        Path testSrcDir = Path.of(Objects.requireNonNull(testEnv.get(TEST_SRCDIR)));
        // A test in an external repository is ../<repo>/<path>
        String runfilePath =
            command.get(1).startsWith("../") ? command.get(1).substring("../".length()) : workspaceName + "/" + command.get(1);
        Path binary;
        if ("1".equals(testEnv.get("RUNFILES_MANIFEST_ONLY"))) {
            Path manifest = testSrcDir.resolve("MANIFEST");
            testEnv.put("RUNFILES_MANIFEST_FILE", manifest.toString());
            String manifestContent;
            try {
                manifestContent = Files.readString(manifest);
            }
            catch (IOException e) {
                throw new UnexpectedScriptContentException("Unable to read the runfiles manifest " + manifest + ": " + e.getMessage());
            }
            // Each manifest line is `<runfile path> <target path>`.
            String target = null;
            for (String line : lines(manifestContent)) {
                if (line.startsWith(runfilePath + " ")) {
                    target = line;
                    break;
                }
            }
            if (target == null) {
                throw new UnexpectedScriptContentException(
                    "Unable to find " + runfilePath + " in the runfiles manifest " + manifest + "."
                );
            }
            binary = Path.of(target.substring((runfilePath + " ").length()));
        }
        else {
            binary = testSrcDir.resolve(runfilePath);
        }

        String preserveCwd = env.get("RUNTEST_PRESERVE_CWD");
        List<Path> directoriesToCreate = new ArrayList<>();
        addIfNotNull(directoriesToCreate, toPathOrNull(testEnv.get(TEST_TMPDIR)));
        addIfNotNull(directoriesToCreate, toPathOrNull(testEnv.get(TEST_UNDECLARED_OUTPUTS_DIR)));
        addIfNotNull(directoriesToCreate, toPathOrNull(testEnv.get(TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR)));
        Path xmlOutputFile = toPathOrNull(testEnv.get(XML_OUTPUT_FILE));
        addIfNotNull(directoriesToCreate, xmlOutputFile != null ? xmlOutputFile.getParent() : null);
        return new ExecutableInfo(
            /* binary = */ binary,
            /* workingDir = */ preserveCwd == null || preserveCwd.isEmpty() ? testSrcDir.resolve(workspaceName) : execRoot,
            // tests go through the wrapper script, so <wrapper> <binary> arg0 ... argN
            /* args = */ List.copyOf(command.subList(2, command.size())),
            /* envVars = */ testEnv,
            /* directoriesToCreate = */ directoriesToCreate
        );
    }

    private static List<String> parseBashWords(String line) throws UnexpectedScriptContentException {
        List<String> words = new ArrayList<>();
        StringBuilder word = new StringBuilder();
        boolean inWord = false;
        boolean inQuotes = false;
        boolean escaped = false;
        for (char c : line.toCharArray()) {
            if (escaped) {
                word.append(c);
                escaped = false;
            }
            else if (inQuotes) {
                if (c == '\'') {
                    inQuotes = false;
                }
                else {
                    word.append(c);
                }
            }
            else if (c == '\'') {
                inQuotes = true;
                inWord = true;
            }
            else if (c == '\\') {
                escaped = true;
                inWord = true;
            }
            else if (c == ' ') {
                if (inWord) {
                    words.add(word.toString());
                }
                word.setLength(0);
                inWord = false;
            }
            else {
                word.append(c);
                inWord = true;
            }
        }
        if (inQuotes) {
            throw new UnexpectedScriptContentException("Unterminated quote: " + line);
        }
        if (inWord) {
            words.add(word.toString());
        }
        return words;
    }

    private static List<String> parseCmdWords(String line) throws UnexpectedScriptContentException {
        List<String> words = new ArrayList<>();
        StringBuilder word = new StringBuilder();
        boolean inWord = false;
        boolean inQuotes = false;
        int backslashes = 0;
        for (char c : line.toCharArray()) {
            if (c == '\\') {
                backslashes++;
                inWord = true;
                continue;
            }
            if (c == '"') {
                word.append("\\".repeat(backslashes / 2));
                if (backslashes % 2 == 1) {
                    word.append('"');
                }
                else {
                    inQuotes = !inQuotes;
                }
                inWord = true;
            }
            else {
                word.append("\\".repeat(backslashes));
                if (c == ' ' && !inQuotes) {
                    if (inWord) {
                        words.add(word.toString());
                    }
                    word.setLength(0);
                    inWord = false;
                }
                else {
                    word.append(c);
                    inWord = true;
                }
            }
            backslashes = 0;
        }
        word.append("\\".repeat(backslashes));
        if (inQuotes) {
            throw new UnexpectedScriptContentException("Unterminated quote: " + line);
        }
        if (inWord) {
            words.add(word.toString());
        }
        return words;
    }

    // consulo: Kotlin String.lines() (also keeps a trailing empty line, unlike Java String.lines())
    private static List<String> lines(String value) {
        return List.of(value.split("\r\n|\n|\r", -1));
    }

    // consulo: Kotlin String.removeSuffix()
    private static String removeSuffix(String value, String suffix) {
        return value.endsWith(suffix) ? value.substring(0, value.length() - suffix.length()) : value;
    }

    // consulo: Kotlin List.dropLast(1)
    private static List<String> dropLast(List<String> list) {
        return list.isEmpty() ? List.of() : List.copyOf(list.subList(0, list.size() - 1));
    }

    private static @Nullable Path toPathOrNull(@Nullable String value) {
        return value != null ? Path.of(value) : null;
    }

    // consulo: Kotlin listOfNotNull()
    private static void addIfNotNull(List<Path> list, @Nullable Path value) {
        if (value != null) {
            list.add(value);
        }
    }

    public static class UnexpectedScriptContentException extends Exception {
        public UnexpectedScriptContentException(String reason) {
            super("Failed to parse Bazel run script. Reason: " + reason);
        }
    }

    private static final String TEST_SRCDIR = "TEST_SRCDIR";
    private static final String TEST_WORKSPACE = "TEST_WORKSPACE";
    private static final String TEST_TMPDIR = "TEST_TMPDIR";

    private static final String XML_OUTPUT_FILE = "XML_OUTPUT_FILE";
    private static final String TEST_UNDECLARED_OUTPUTS_DIR = "TEST_UNDECLARED_OUTPUTS_DIR";
    private static final String TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR = "TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR";

    private static final List<String> RELATIVE_PATH_VARS_TO_RESOLVE = List.of(
        TEST_SRCDIR,
        TEST_TMPDIR,
        XML_OUTPUT_FILE,
        TEST_UNDECLARED_OUTPUTS_DIR,
        TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR,
        "TEST_PREMATURE_EXIT_FILE",
        "TEST_WARNINGS_OUTPUT_FILE",
        "TEST_LOGSPLITTER_OUTPUT_FILE",
        "TEST_INFRASTRUCTURE_FAILURE_FILE",
        "TEST_UNUSED_RUNFILES_LOG_FILE",
        "RUNFILES_DIR",
        "JAVA_RUNFILES",
        "PYTHON_RUNFILES",
        "HOME"
    );

    private static final List<String> VARS_TO_UNSET = List.of(
        "TEST_UNDECLARED_OUTPUTS_MANIFEST",
        "TEST_UNDECLARED_OUTPUTS_ZIP",
        "TEST_UNDECLARED_OUTPUTS_ANNOTATIONS"
    );
}
